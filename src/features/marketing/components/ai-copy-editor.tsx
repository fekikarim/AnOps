"use client";

import { useToast } from "@/shared/components/ui/toast";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { useState, useTransition } from "react";
import { approveCopyAction, editCopyAction, applyCopyToSocialPostAction, applyCopyToCampaignAction } from "@/features/marketing/actions/ai.action";
import { Button, selectClass, textareaClass } from "@/shared/components/ui/button";
import { StatusBadge } from "@/shared/components/data-display/status-badge";
import type { AiGenerationDto } from "@/server/marketing/ai/copy.service";
import { CHANNEL_LABELS } from "@/features/marketing/labels";

const STATUS_TONE: Record<AiGenerationDto["status"], "success" | "warning" | "error" | "neutral" | "info"> = {
  generated_draft: "warning",
  edited: "warning",
  approved_for_use: "success",
  failed: "error",
};
const STATUS_LABEL: Record<AiGenerationDto["status"], string> = {
  generated_draft: "Draft · not approved",
  edited: "Edited · not approved",
  approved_for_use: "Approved for use",
  failed: "Failed",
};

/**
 * Draft review. The text is editable; approval is an explicit button; placing text into a campaign or post
 * is a second explicit action, and each of those actions is re-checked on the server.
 */
export function AiCopyEditor({
  generation,
  campaigns,
  socialAccounts,
  canGenerate,
  canManageCampaigns,
  canManageSocial,
}: {
  generation: AiGenerationDto;
  campaigns: { id: string; name: string; channel: string; version: number }[];
  socialAccounts: { id: string; name: string }[];
  canGenerate: boolean;
  canManageCampaigns: boolean;
  canManageSocial: boolean;
}) {
  const router = useRouter();
  const [pending, startTransition] = useTransition();
  const toast = useToast();
  const current = generation.current ?? { subject: "", body: "" };
  const [subject, setSubject] = useState(current.subject);
  const [body, setBody] = useState(current.body);
  const [campaignId, setCampaignId] = useState("");
  const [accountId, setAccountId] = useState("");
  const isEmail = generation.channel === "email";
  const compatible = campaigns.filter((campaign) => campaign.channel === generation.channel);
  const editable = canGenerate && generation.status !== "failed";

  const run = (task: () => Promise<{ ok: boolean; error?: { message: string } }>, success: string) =>
    startTransition(async () => {
      const result = await task();
      if (!result.ok) return toast.fromError(result.error);
      toast.success(success);
      router.refresh();
    });

  if (generation.status === "failed") {
    return (
      <section aria-labelledby="draft" className="space-y-3 rounded-[var(--radius-card)] border border-[var(--color-status-error)] bg-[var(--color-bg-surface)] p-5">
        <h2 id="draft" className="text-base font-semibold">Generation failed</h2>
        <p role="alert" className="text-sm text-[var(--color-status-error)]">{generation.errorMessage}</p>
        <Link href="/marketing/ai" className="inline-flex min-h-[44px] items-center text-sm underline">Try again with a new brief</Link>
      </section>
    );
  }

  return (
    <div className="space-y-6">
      <section aria-labelledby="draft" className="space-y-4 rounded-[var(--radius-card)] border border-[var(--color-border-subtle)] bg-[var(--color-bg-surface)] p-5">
        <div className="flex flex-wrap items-center justify-between gap-3">
          <h2 id="draft" className="text-base font-semibold">Draft</h2>
          <StatusBadge label={STATUS_LABEL[generation.status]} tone={STATUS_TONE[generation.status]} />
        </div>
        {isEmail && (
          <div className="space-y-1.5">
            <label htmlFor="ai-subject" className="text-sm font-semibold">Subject</label>
            <input id="ai-subject" maxLength={150} value={subject} disabled={!editable} onChange={(event) => setSubject(event.target.value)} className="min-h-[44px] w-full rounded-[var(--radius-control)] border border-[var(--color-border-control)] bg-[var(--color-bg-surface)] px-3 text-sm" />
          </div>
        )}
        <div className="space-y-1.5">
          <label htmlFor="ai-body" className="text-sm font-semibold">Copy</label>
          <textarea id="ai-body" rows={7} value={body} disabled={!editable} onChange={(event) => setBody(event.target.value)} className={textareaClass} />
          <p className="text-xs text-[var(--color-text-secondary)]" aria-live="polite">{body.length} characters</p>
        </div>
        <p className="text-xs text-[var(--color-text-secondary)]">Generated by {generation.providerName ?? "the AI provider"}{generation.modelName ? ` (${generation.modelName})` : ""}. Review every claim and price before use.</p>
        {editable && (
          <div className="flex flex-col gap-2 sm:flex-row sm:justify-end">
            <Button disabled={pending || (subject === current.subject && body === current.body)} onClick={() => run(() => editCopyAction(generation.id, { subject, body, expectedVersion: generation.version }), "Edits saved. Approve the copy again before using it.")}>
              Save edits
            </Button>
            {generation.status !== "approved_for_use" && (
              <Button variant="primary" disabled={pending} onClick={() => run(() => approveCopyAction(generation.id, { expectedVersion: generation.version }), "Approved for use.")}>
                Approve for use
              </Button>
            )}
          </div>
        )}
      </section>

      {generation.status === "approved_for_use" && (
        <section aria-labelledby="use" className="grid gap-4 md:grid-cols-2">
          {generation.channel !== "facebook_page" && canManageCampaigns && (
            <div className="space-y-3 rounded-[var(--radius-card)] border border-[var(--color-border-subtle)] bg-[var(--color-bg-surface)] p-5">
              <h2 id="use" className="text-base font-semibold">Use in a draft campaign</h2>
              {compatible.length === 0 ? (
                <p className="text-sm text-[var(--color-text-secondary)]">No draft {CHANNEL_LABELS[generation.channel as "email" | "sms" | "telegram"]} campaign exists. <Link className="underline" href="/marketing/campaigns/new">Create one</Link>.</p>
              ) : (
                <>
                  <label htmlFor="campaign-target" className="text-sm font-semibold">Campaign</label>
                  <select id="campaign-target" className={selectClass} value={campaignId} onChange={(event) => setCampaignId(event.target.value)}>
                    <option value="">Choose a campaign</option>
                    {compatible.map((campaign) => <option key={campaign.id} value={campaign.id}>{campaign.name}</option>)}
                  </select>
                  <Button disabled={pending || !campaignId || generation.status !== "approved_for_use"} onClick={() => {
                    const target = compatible.find((item) => item.id === campaignId);
                    if (!target) return;
                    run(() => applyCopyToCampaignAction(generation.id, { campaignId, expectedVersion: target.version }), "Copy added to the draft. Recipients were not changed.");
                  }}>
                    Copy into campaign draft
                  </Button>
                </>
              )}
            </div>
          )}
          {generation.channel === "facebook_page" && canManageSocial && (
            <div className="space-y-3 rounded-[var(--radius-card)] border border-[var(--color-border-subtle)] bg-[var(--color-bg-surface)] p-5">
              <h2 id="use" className="text-base font-semibold">Create a social post draft</h2>
              {socialAccounts.length === 0 ? (
                <p className="text-sm text-[var(--color-text-secondary)]">Connect a Facebook Page first. <Link className="underline" href="/marketing/social">Go to social</Link></p>
              ) : (
                <>
                  <label htmlFor="account-target" className="text-sm font-semibold">Page</label>
                  <select id="account-target" className={selectClass} value={accountId} onChange={(event) => setAccountId(event.target.value)}>
                    <option value="">Choose a Page</option>
                    {socialAccounts.map((account) => <option key={account.id} value={account.id}>{account.name}</option>)}
                  </select>
                  <Button disabled={pending || !accountId} onClick={() => run(async () => {
                    const result = await applyCopyToSocialPostAction(generation.id, { socialAccountId: accountId });
                    if (result.ok) router.push(`/marketing/social/posts/${result.data.id}`);
                    return result;
                  }, "Post draft created. It is not scheduled.")}>
                    Create draft post
                  </Button>
                </>
              )}
            </div>
          )}
        </section>
      )}
      {!editable && generation.status !== "approved_for_use" && <span className="sr-only">Read only</span>}
    </div>
  );
}
